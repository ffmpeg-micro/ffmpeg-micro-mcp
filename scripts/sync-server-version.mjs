#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';

const version = JSON.parse(readFileSync('package.json', 'utf8')).version;
const server = JSON.parse(readFileSync('server.json', 'utf8'));

server.version = version;
for (const pkg of server.packages ?? []) pkg.version = version;

writeFileSync('server.json', JSON.stringify(server, null, 2) + '\n');
console.log(`server.json synced to ${version}`);

// The MCP server reports this in its initialize response. It is a generated
// constant rather than a runtime read of package.json so the Vercel bundle
// never depends on package.json being traced into the function.
writeFileSync(
  'src/version.ts',
  `// Generated by scripts/sync-server-version.mjs. Do not edit by hand.\nexport const SERVER_VERSION = "${version}";\n`,
);
console.log(`src/version.ts synced to ${version}`);
